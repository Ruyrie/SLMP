import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } })
await page.goto('http://8.208.12.217/login', { waitUntil: 'domcontentloaded', timeout: 60000 })
await page.waitForTimeout(1500)
await page.getByPlaceholder('请输入手机号').fill('13800006620')
await page.getByPlaceholder('请输入密码').fill('Zmt12345')
await page.getByRole('button', { name: '登录' }).click()
await page.waitForURL((u) => !u.pathname.startsWith('/login'), { timeout: 30000 }).catch(() => undefined)
await page.waitForTimeout(3000)
await page.goto('http://8.208.12.217/messages', { waitUntil: 'domcontentloaded', timeout: 60000 })
await page.waitForTimeout(4500)
await page.screenshot({ path: 'D:/Android_Program/SLMP/logs/diag/verify-messages.png' })
const info = await page.evaluate(() => ({ text: document.body.innerText.slice(0, 700) }))
console.log(JSON.stringify(info, null, 1))
await browser.close()
