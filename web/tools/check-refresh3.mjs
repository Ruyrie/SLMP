import { chromium } from 'playwright'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const context = await browser.newContext({ viewport: { width: 1440, height: 900 } })
const page = await context.newPage()
const events = []
page.on('response', (res) => {
  if (res.url().includes('/auth/')) events.push({ url: res.url().replace('http://127.0.0.1:5173', ''), status: res.status() })
})
await page.goto('http://127.0.0.1:5173/login', { waitUntil: 'networkidle' })
await page.getByPlaceholder('请输入手机号').fill('13800006620')
await page.getByPlaceholder('请输入密码').fill('Zmt12345')
await page.getByRole('button', { name: '登录' }).click()
await page.waitForURL((url) => !url.pathname.startsWith('/login'), { timeout: 20000 })
await page.waitForTimeout(1500)
console.log('after login:', page.url(), JSON.stringify(await context.cookies()))
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
console.log('after /:', page.url(), JSON.stringify(await context.cookies()))
console.log('events /:', JSON.stringify(events))
events.length = 0
await page.goto('http://127.0.0.1:5173/calendar', { waitUntil: 'networkidle' })
await page.waitForTimeout(1200)
console.log('after calendar:', page.url(), JSON.stringify(await context.cookies()))
console.log('events calendar:', JSON.stringify(events))
await browser.close()
